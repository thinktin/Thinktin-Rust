    /// 已决的审批卡片上的结论（`ApprovalOutcome`）。
    public static func approvalOutcome(_ outcome: ApprovalOutcome, optionName: String?, language: DisplayLanguage)
        -> String
    {
        let zh = language == .chinese
        let option = optionName.flatMap { $0.isEmpty ? nil : $0 }
        switch outcome {
        case .approvedByUser:
            if let option { return zh ? "你批准了：\(option)" : "You approved: \(option)" }
            return zh ? "你批准了" : "You approved"
        case .rejectedByUser:
            if let option { return zh ? "你拒绝了：\(option)" : "You declined: \(option)" }
            return zh ? "你拒绝了" : "You declined"
        case .approvedByPolicy: return zh ? "已按预授权批准" : "Approved by your pre-authorization"
        case .rejectedByPolicy: return zh ? "已按策略拒绝" : "Declined by policy"
        case .expired: return zh ? "已过期，没有处理" : "Expired without a decision"
        case .cancelled: return zh ? "已作废（这一轮已经结束）" : "No longer needed (this attempt ended)"
        }
    }

