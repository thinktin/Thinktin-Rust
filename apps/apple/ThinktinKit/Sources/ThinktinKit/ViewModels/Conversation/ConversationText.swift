    /// 遮住中间的值：“sk-a…Q7mA”。
    public static func maskedValue(_ value: String) -> String {
        guard value.count > 10 else { return String(repeating: "•", count: max(4, value.count)) }
        return String(value.prefix(4)) + "…" + String(value.suffix(4))
    }

