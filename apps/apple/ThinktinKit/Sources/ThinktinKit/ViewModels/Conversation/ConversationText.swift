/// 对话与运行过程（WBS 12.5）界面上的文案：中英文都在这里，界面按 `DisplayLanguage` 取。
///
/// 接口的英文说明（`ClientError` 的 `message`、运行的失败原因、agent 报错）不当正文显示：正文按种类、状态本地化，
