    /// 剩余时间：“还剩 3 小时”“即将过期”。
    public static func approvalExpiry(_ expiresAt: Date, now: Date, language: DisplayLanguage) -> String {
        let zh = language == .chinese
        let left = expiresAt.timeIntervalSince(now)
        if left <= 0 { return zh ? "已到期" : "Expired" }
        if left < 60 { return zh ? "即将过期" : "Expires soon" }
        let text = Formatting.duration(left >= 3600 ? (left / 3600).rounded(.down) * 3600 : left, language: language)
        return zh ? "还剩 \(text)" : "\(text) left"
    }

