    /// 复制、分享 agent 输出时追加在末尾的标识（和服务端 `proto::labels::text_footer_in` 一致）。
    public static func copyFooter(_ language: DisplayLanguage) -> String {
        switch language {
        case .chinese: "\n\n——本内容由人工智能生成（\(provider)）\n"
        case .english: "\n\n— This content was generated by AI (\(provider))\n"
        }
    }

    /// 复制、分享出去的文字：原文加上标识。
    public static func copyText(_ text: String, language: DisplayLanguage) -> String {
        text.trimmingCharacters(in: .whitespacesAndNewlines) + copyFooter(language)
    }

