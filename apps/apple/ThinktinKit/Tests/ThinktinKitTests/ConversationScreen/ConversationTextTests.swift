import Foundation
import Testing

@testable import ThinktinKit

@Suite("对话页的文案与规则")
struct ConversationTextTests {
    @Test("AI 生成标识的规则表：只有 agent 写的标；任务按来源（委派、流水线、agent 建的计划）")
    func aiRules() {
        let labelled = AIGeneratedField.allCases.filter(\.isAIGenerated)
        #expect(labelled.contains(.agentMessage) && labelled.contains(.toolCallTitle) && labelled.contains(.runSummary))
        #expect(!AIGeneratedField.userPrompt.isAIGenerated)
        #expect(!AIGeneratedField.runError.isAIGenerated)
        #expect(!AIGeneratedField.quotaReason.isAIGenerated)
        func prompt(_ source: RunSource, _ author: PlanAuthor? = nil) -> Bool {
            AIGeneratedField.prompt(of: Fixture.run("r", source: source), planAuthor: author).isAIGenerated
        }
        #expect(!prompt(.user))
        #expect(prompt(.delegate))
        #expect(prompt(.pipeline))
        #expect(prompt(.plan, .agent))
        #expect(!prompt(.plan, .user))
        #expect(!prompt(.plan))
        #expect(AIGeneratedField.stateReason(for: .waitingApproval).isAIGenerated)
        #expect(!AIGeneratedField.stateReason(for: .waitingQuota).isAIGenerated)
        #expect(!AIGeneratedField.stateReason(for: .failed).isAIGenerated)
        #expect(AIGeneratedField.planTitle(createdBy: .agent) == .agentPlanTitle)
    }

    @Test("复制、分享带的标识和服务端 proto::labels::text_footer_in 一致")
    func copyFooter() {
        #expect(ConversationText.copyFooter(.chinese) == "\n\n——本内容由人工智能生成（ThinkTin）\n")
        #expect(ConversationText.copyFooter(.english) == "\n\n— This content was generated by AI (ThinkTin)\n")
        #expect(ConversationText.copyText("  答案\n", language: .chinese) == "答案\n\n——本内容由人工智能生成（ThinkTin）\n")
    }

    @Test("运行状态行：等 key 按等待原因码分“去处理”和“稍后自动继续”，等电脑、等子任务、等审批各有下一步")
    func statusPresentation() {
        func present(_ line: RunStatusLine, _ language: DisplayLanguage = .chinese) -> RunStatusPresentation {
            RunStatusPresentation(line: line, language: language)
        }
        let invalid = present(RunStatusLine(state: .waitingQuota, reason: "key 失效了", waitCode: .invalid))
        #expect(invalid.action == .openModelRoutes)
        #expect(invalid.detail == "key 失效了", "服务端按用户语言写的说明当正文")
        #expect(!invalid.reasonIsAIGenerated)
        let limited = present(RunStatusLine(state: .waitingQuota, waitCode: .rateLimited))
        #expect(limited.action == nil)
        #expect(limited.headline.contains("稍后自动继续"))
        let noCode = present(RunStatusLine(state: .waitingQuota))
        #expect(noCode.action == .openModelRoutes)
        let device = present(RunStatusLine(state: .waitingDevice, waitCode: .deviceOffline))
        #expect(device.headline == "等电脑上线")
        #expect(device.action == nil)
        let approval = present(RunStatusLine(state: .waitingApproval, reason: "发送消息到「研发群」"))
        #expect(approval.action == .scrollToApproval)
        #expect(approval.reason == "发送消息到「研发群」")
        #expect(approval.reasonIsAIGenerated, "等审批的说明是 agent 写的审批标题")
        #expect(approval.detail == nil)
        #expect(present(RunStatusLine(state: .waitingChildren)).action == .openRunTree)
        let failed = present(
            RunStatusLine(
                state: .failed, reason: "x", tokensUsed: 18_000, error: "model gateway: credential rate limited",
                startedAt: Fixture.now, finishedAt: Fixture.now.addingTimeInterval(90)))
        #expect(failed.headline == "任务失败")
        #expect(failed.reason == "model gateway: credential rate limited", "英文诊断放进详情")
        #expect(failed.detail == "用时 1 分 30 秒 · 1.8 万 token")
        let retry = present(RunStatusLine(state: .running, attempt: 2), .english)
        #expect(retry.detail == "Attempt 2, resumed where it left off")
        let starting = RunStatusPresentation(
            line: RunStatusLine(state: .starting), instanceState: .archived, language: .chinese)
        #expect(starting.detail?.contains("从模板重建") == true)
    }

    @Test("工具调用卡片：命令、路径做摘要，展开看参数和结果；平台工具显示类别")
    func toolPresentation() {
        let run = ToolCallCard(
            toolCallID: "t1", title: "运行测试", kind: "execute", status: .completed,
            raw: [
                "rawInput": ["command": ["swift", "test", "--parallel"]],
                "content": [["type": "content", "content": ["type": "text", "text": "128 tests passed"]]],
            ])
        let p = ToolCallPresentation(run, language: .chinese)
        #expect(p.kindName == "执行命令")
        #expect(p.summary == "swift test --parallel")
        #expect(p.output == "128 tests passed")
        #expect(p.statusName == "完成")
        #expect(p.input?.contains("--parallel") == true)
        #expect(ToolCallPresentation.isAIGenerated(run))

        let read = ToolCallPresentation(
            ToolCallCard(toolCallID: "t2", title: "", kind: "read", raw: ["rawInput": ["path": "notes/weekly.md"]]),
            language: .english)
        #expect(read.title == "Read", "没有标题时用种类名")
        #expect(read.summary == "notes/weekly.md")

        let platform = ToolCallPresentation(
            ToolCallCard(
                toolCallID: "p1", title: "schedule_create", raw: ["title": "每周依赖检查", "cron": "0 9 * * 1"],
                platformCategory: .plan), language: .chinese)
        #expect(platform.kindName == "平台工具 · 计划")
        #expect(platform.summary == "每周依赖检查")
        #expect(platform.statusName == nil)
    }

    @Test("拦截弹层里遮住的值、条目名规则")
    func secretsText() {
        #expect(ConversationText.maskedValue("sk-ant-abcdefghijklmnop") == "sk-a…mnop")
        #expect(ConversationText.maskedValue("short") == "•••••")
        #expect(VaultNameProblem.check("github_2") == nil)
        #expect(VaultNameProblem.check("") == .empty)
        #expect(VaultNameProblem.check("_x") == .invalidCharacters)
        #expect(VaultNameProblem.check("GitHub") == .invalidCharacters)
        #expect(VaultNameProblem.check(String(repeating: "a", count: 65)) == .tooLong)
    }

    @Test("审批的剩余时间、结论")
    func approvalTexts() {
        let now = Fixture.now
        #expect(
            ConversationText.approvalExpiry(now.addingTimeInterval(5 * 3600 + 120), now: now, language: .chinese)
                == "还剩 5 小时")
        #expect(
            ConversationText.approvalExpiry(now.addingTimeInterval(30), now: now, language: .english) == "Expires soon")
        #expect(ConversationText.approvalExpiry(now, now: now, language: .chinese) == "已到期")
        #expect(
            ConversationText.approvalOutcome(.approvedByUser, optionName: "允许一次", language: .chinese) == "你批准了：允许一次")
        #expect(
            ConversationText.approvalOutcome(.expired, optionName: nil, language: .english)
                == "Expired without a decision")
    }

    @Test("每一种系统提示、来源分隔头都有中英文")
    func everyNotice() {
        let kinds: [SystemNotice.Kind] = [
            .agentError, .sessionLost, .agentExited(willRestart: true), .agentExited(willRestart: false), .logTruncated,
            .vaultUsed(["github", "npm"]), .turnStopped(.refusal), .turnStopped(.maxTokens),
            .turnStopped(.maxTurnRequests),
        ]
        for kind in kinds {
            #expect(!ConversationText.systemNotice(kind, language: .chinese).isEmpty)
            #expect(!ConversationText.systemNotice(kind, language: .english).isEmpty)
        }
        #expect(
            ConversationText.systemNotice(.vaultUsed(["github", "npm"]), language: .chinese) == "用了保险箱里的 github、npm")
        #expect(
            ConversationText.sourceHeader(source: .plan, planTitle: "每日汇总", stepKey: nil, language: .chinese)
                == "计划触发 · 每日汇总")
        #expect(ConversationText.sourceHeader(source: .user, planTitle: nil, stepKey: nil, language: .chinese) == nil)
        #expect(
            ConversationText.sourceHeader(source: .pipeline, planTitle: nil, stepKey: "review", language: .english)
                == "Pipeline step · review")
    }

    @Test("agent 回复里的链接：深链在 App 里打开，网址、邮件交给系统，别的不打开")
    func links() {
        func handling(_ string: String) -> ConversationLinks.Handling {
            URL(string: string).map(ConversationLinks.handling(of:)) ?? .blocked
        }
        #expect(handling("https://example.com/a?b=1") == .external)
        #expect(handling("HTTP://example.com") == .external)
        #expect(handling("mailto:dev@example.com") == .external)
        #expect(handling("thinktin://run/abc") == .inApp)
        #expect(handling("tel:10086") == .blocked)
        #expect(handling("sms:10086") == .blocked)
        #expect(handling("javascript:alert(1)") == .blocked)
        #expect(handling("file:///etc/hosts") == .blocked)
        #expect(handling("weixin://dl/business") == .blocked)
        #expect(handling("https:foo") == .blocked, "没有主机")
        #expect(handling("mailto:") == .blocked, "没有收件人")
        #expect(handling("relative/path") == .blocked)
    }
}
