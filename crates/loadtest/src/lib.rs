//! 压测工具（WBS 17.5）。三个场景，都在一个进程里把被测组件和负载一起跑起来：
//!
//! - [`trigger_storm`]：整点触发洪峰。成千上万个计划在同一时刻到点，多个调度器副本同时扫描，
//!   看多久全部生成运行、有没有重复或漏掉、削峰抖动把启动时间摊得多平。
//! - [`wake_storm`]：并发唤醒。一批暂停着的实例同时被唤醒（同一个实例可以被多次唤醒），
//!   看唤醒延迟分布、每个实例是不是只恢复了一次沙箱。沙箱后端是本地后端外面包一层固定延迟，模拟 Cube 的恢复耗时。
//! - [`llm_stream`]：模型网关流式吞吐。真实的网关（验令牌、换 key、改模型名、计量）接一个按设定速度吐 SSE 的假厂商，
//!   并发发流式请求，看首字节延迟、总耗时、吞吐，并核对流是逐字节透传的；可以同时测一遍直连假厂商作为基线，
//!   差值就是网关的开销。也可以指向部署好的网关（`--gateway`）。
//!
//! 前两个场景要 Postgres：在给定的服务器上新建一个临时库（[`scratch`]），跑迁移、造数据、测完删掉，不碰已有的库。
//! 本地和 CI 用小规模跑通（`tests/`），正式的数字在 2.4 部署好的预发环境上跑。

pub mod llm_stream;
pub mod scratch;
pub mod stats;
pub mod trigger_storm;
pub mod wake_storm;
